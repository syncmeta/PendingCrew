import Foundation

/// **一条「这次没写进去」的回执长什么样** —— 全仓唯一一份措辞。
///
/// ## 为什么要有这一份
///
/// 这一族缺陷的形状是：**回执描述的是「我调用了写入函数」，不是「写入成功了」。**
/// 成功和失败在调用方那儿长得一模一样，所以没有人会回来查。三个真实现场：
///
/// * `report_to_parent` 在数据目录读写失败的窗口里回「已提交向上汇报」，
///   而那段时间父 crew 白板上一条都没有。
/// * `respond_todo` 写不进账本时照样回「已回应」。
/// * `post_to_crew` 的 `reply_to` 行为不对时回执照回「已发到」。
///
/// 口径是拍过的：**宁可回一条难看的失败，也不要回一条好看的成功。**
///
/// ## `notWrittenMarker` 为什么是一个记号而不是一句话
///
/// 措辞会随场景变（写的是白板还是账本、后果是什么），但**「这次没写进去」这件事
/// 必须有一个不会漂的抓手** —— 尺子（`McpWriteFailureHonestyTests`）认的就是它。
/// 换成靠正则去猜「这句话读起来像不像失败」，就是又造了一把措辞一变就静默失效的尺子。
///
/// 记号带方括号是刻意的：它不可能在一句成功回执里意外出现，所以
/// 「带了 = 失败」和「没带 = 成功」两个方向都判得死。
enum WriteReceipt {

    /// 每一条「这次写盘没成功」的回执都必须包含它。**成功回执里绝不许出现。**
    static let notWrittenMarker = "【没写进去】"

    /// 拼一条失败回执。
    ///
    /// - Parameters:
    ///   - what: 本来要写的那件事（「向上汇报」「这条回应」「这条群消息」）。
    ///   - consequence: **对调用方来说意味着什么** —— 一个 agent 读完要知道该干什么。
    ///     只说「失败了」它会瞎重试；说清「对方群里什么都没有」它才知道要换条路。
    ///   - error: 底层错误（有就带上，排查时那句原文比我们的转述硬）。
    static func notWritten(what: String, error: Error? = nil, consequence: String) -> String {
        var text = "ERROR: \(what)\(notWrittenMarker)"
        if let error { text += " —— \(error.localizedDescription)" }
        return text + "。" + consequence
    }

    /// 记号的准确语义：**这次调用要求写的东西没有全部落盘。**
    ///
    /// 所以「账落了、群里那行没发出去」这种半截也带它 —— 那一半确实没写进去，
    /// 而 agent 需要因此改变行为（自己去群里补一句）。回执正文负责说清
    /// 哪一半成了、哪一半没成；记号只负责让「有东西没写上」这件事无法被略过。
    ///
    /// 反过来：**全都写成功了就绝不许带它**（`McpWriteFailureHonestyTests`
    /// 的第二半盯着这个方向）。一把永远红的尺子跟一把永远绿的一样没用。
    static let markerMeaning = "这次调用要求写的东西没有全部落盘"

}
